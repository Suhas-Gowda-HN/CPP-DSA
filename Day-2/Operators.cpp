    cout<<c<<endl;
    cout<<d<<endl;
    cout<<e<<endl;
    cout<<f<<endl;
    cout<<a2<<endl;
    cout<<a1;

    // Arithmetic Operators

    // Relational Operators

    cout<<(a==b)<<endl; // if a and b value are equal it prints true(1) in binary else false(0) in binary

